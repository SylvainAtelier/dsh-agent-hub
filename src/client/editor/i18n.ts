const english = (): boolean =>
  typeof document !== 'undefined' && document.documentElement.lang.toLowerCase().startsWith('en')

export function t(key: EditorKey, params?: Record<string, string | number>): string {
  const text: string = (english() ? en : zh)[key] ?? key
  if (params === undefined) return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match))
}

export const isMac = (): boolean => typeof navigator !== 'undefined' && /Mac|iPhone|iPad/.test(navigator.platform)

/** The workspace search shortcut: Ctrl/⌘+Shift+F in the desktop app, Ctrl/⌘+Alt+F in a browser (see index.tsx). */
export const SEARCH_KEY = (): string =>
  (typeof window !== 'undefined' && '__DSH_HOST_PATHS__' in window ? 'Mod-Shift-F' : 'Mod-Alt-F')

/** A shortcut written for this platform: `Mod-Shift-f` → `Ctrl+Shift+F` / `⌘⇧F`. */
export function keyHint(spec: string): string {
  const mac = isMac()
  return spec.split('-').map((part) => {
    if (part === 'Mod') return mac ? '⌘' : 'Ctrl'
    if (part === 'Shift') return mac ? '⇧' : 'Shift'
    if (part === 'Alt') return mac ? '⌥' : 'Alt'
    return part.length === 1 ? part.toUpperCase() : part
  }).join(mac ? '' : '+')
}
