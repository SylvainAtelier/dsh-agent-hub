const isEnglish = (): boolean =>
  typeof document !== 'undefined' && document.documentElement.lang.toLowerCase().startsWith('en')

export function t(key: Key, params?: Record<string, string | number>): string {
  let text = (isEnglish() ? en : zh)[key] ?? key
  for (const [name, value] of Object.entries(params ?? {})) text = text.replaceAll(`{${name}}`, String(value))
  return text
}

const MINUTE = 60_000
const HOUR = 60 * MINUTE
const DAY = 24 * HOUR

/** A future span, coarse enough to read at a glance: "3 小时 12 分". */
export function duration(ms: number): string {
  const total = Math.max(0, ms)
  if (total >= DAY) return t('dur.d', { d: Math.floor(total / DAY), h: Math.floor((total % DAY) / HOUR) })
  if (total >= HOUR) return t('dur.h', { h: Math.floor(total / HOUR), m: Math.floor((total % HOUR) / MINUTE) })
  return t('dur.m', { m: Math.max(1, Math.ceil(total / MINUTE)) })
}

/** The same span for tight columns: "3时29分". */
export function shortDuration(ms: number): string {
  const total = Math.max(0, ms)
  if (total >= DAY) return t('short.d', { d: Math.floor(total / DAY), h: Math.floor((total % DAY) / HOUR) })
  if (total >= HOUR) return t('short.h', { h: Math.floor(total / HOUR), m: Math.floor((total % HOUR) / MINUTE) })
  return t('short.m', { m: Math.max(1, Math.ceil(total / MINUTE)) })
}

export function ago(at: number, now: number): string {
  const span = now - at
  if (span < MINUTE) return t('ago.now')
  if (span < HOUR) return t('ago.m', { n: Math.floor(span / MINUTE) })
  if (span < DAY) return t('ago.h', { n: Math.floor(span / HOUR) })
  return t('ago.d', { n: Math.floor(span / DAY) })
}

export const dateTime = (at: number): string =>
  new Date(at).toLocaleString(isEnglish() ? 'en' : 'zh-CN', { month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' })

export const date = (at: number): string =>
  new Date(at).toLocaleDateString(isEnglish() ? 'en' : 'zh-CN', { year: 'numeric', month: 'short', day: 'numeric' })
