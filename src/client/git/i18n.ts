const english = (): boolean =>
  typeof document !== 'undefined' && document.documentElement.lang.toLowerCase().startsWith('en')

export function t(key: GitKey, params?: Record<string, string | number>): string {
  const text: string = (english() ? en : zh)[key] ?? key
  if (params === undefined) return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match))
}

export function ago(at: number, now = Date.now()): string {
  const s = Math.max(0, (now - at) / 1000)
  if (s < 60) return t('now')
  if (s < 3600) return t('ago.m', { n: Math.floor(s / 60) })
  if (s < 86400) return t('ago.h', { n: Math.floor(s / 3600) })
  if (s < 86400 * 30) return t('ago.d', { n: Math.floor(s / 86400) })
  if (s < 86400 * 365) return t('ago.mo', { n: Math.floor(s / 86400 / 30) })
  return t('ago.y', { n: Math.floor(s / 86400 / 365) })
}

export const fullDate = (at: number): string =>
  new Date(at).toLocaleString(english() ? 'en' : 'zh-CN', { dateStyle: 'medium', timeStyle: 'short' })

export const primaryKey = (): string =>
  typeof navigator !== 'undefined' && /Mac|iPhone|iPad/.test(navigator.platform) ? '⌘↵' : 'Ctrl+↵'
